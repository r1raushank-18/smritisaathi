'use client'
import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'
import { patient, family, schedule, medicines, games, progressData, emergencyContacts } from './smriti-data'

// Warm gradient-like header via solid fills (PDF has no gradient primitive)
function drawHeader(doc, title, subtitle) {
  const w = doc.internal.pageSize.getWidth()
  // Sky
  doc.setFillColor(14, 165, 233); doc.rect(0, 0, w, 70, 'F')
  // Violet accent right
  doc.setFillColor(139, 92, 246); doc.rect(w * 0.55, 0, w * 0.45, 70, 'F')
  // Teal small accent
  doc.setFillColor(20, 184, 166); doc.rect(w * 0.82, 0, w * 0.18, 70, 'F')

  doc.setTextColor(255, 255, 255)
  doc.setFont('helvetica', 'bold'); doc.setFontSize(22)
  doc.text('SmritiSaathi', 40, 34)
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10)
  doc.text('AI Memory Companion • Weekly Care Report', 40, 52)

  doc.setTextColor(30, 41, 59)
  doc.setFont('helvetica', 'bold'); doc.setFontSize(18)
  doc.text(title, 40, 110)
  if (subtitle) { doc.setFont('helvetica', 'normal'); doc.setFontSize(11); doc.setTextColor(100, 116, 139); doc.text(subtitle, 40, 128) }
}

function drawFooter(doc, pageNum, totalPages) {
  const w = doc.internal.pageSize.getWidth()
  const h = doc.internal.pageSize.getHeight()
  doc.setDrawColor(226, 232, 240); doc.line(40, h - 40, w - 40, h - 40)
  doc.setFontSize(9); doc.setTextColor(100, 116, 139)
  doc.text('Generated by SmritiSaathi • Confidential', 40, h - 24)
  doc.text(`Page ${pageNum} / ${totalPages}`, w - 90, h - 24)
}

function sectionTitle(doc, y, text, color = [14, 165, 233]) {
  doc.setFillColor(color[0], color[1], color[2]); doc.roundedRect(40, y - 12, 6, 16, 2, 2, 'F')
  doc.setTextColor(30, 41, 59); doc.setFont('helvetica', 'bold'); doc.setFontSize(13)
  doc.text(text, 54, y)
  return y + 10
}

export function generateWeeklyReport() {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const w = doc.internal.pageSize.getWidth()
  const now = new Date()
  const weekEnd = now.toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })
  const weekStart = new Date(now.getTime() - 6 * 86400000).toLocaleDateString('en-IN', { day: 'numeric', month: 'long' })

  drawHeader(doc, `Care Report for ${patient.name}`, `Week: ${weekStart} — ${weekEnd}`)

  // Patient snapshot card
  let y = 160
  doc.setFillColor(248, 250, 252); doc.roundedRect(40, y, w - 80, 90, 10, 10, 'F')
  doc.setTextColor(30, 41, 59); doc.setFont('helvetica', 'bold'); doc.setFontSize(14)
  doc.text(patient.name, 60, y + 28)
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(100, 116, 139)
  doc.text(`Age ${patient.age}  •  ${patient.hometown}`, 60, y + 46)
  doc.text(`Favorite food: ${patient.favorite_food}`, 60, y + 62)

  // KPI badges
  const kpis = [
    { l: 'Memory Score', v: `${patient.memoryScore}%`, c: [139, 92, 246] },
    { l: 'Streak', v: `${patient.streak} days`, c: [20, 184, 166] },
    { l: 'Adherence', v: '92%', c: [14, 165, 233] },
    { l: 'Mood', v: '4.8 / 5', c: [244, 63, 94] },
  ]
  kpis.forEach((k, i) => {
    const x = w - 80 - (kpis.length - i) * 90 + 90
    doc.setFillColor(k.c[0], k.c[1], k.c[2]); doc.roundedRect(x, y + 18, 78, 54, 8, 8, 'F')
    doc.setTextColor(255, 255, 255); doc.setFont('helvetica', 'bold'); doc.setFontSize(13)
    doc.text(k.v, x + 8, y + 42)
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8)
    doc.text(k.l, x + 8, y + 60)
  })

  // Summary paragraph
  y += 110
  y = sectionTitle(doc, y, 'AI Weekly Summary', [139, 92, 246])
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10.5); doc.setTextColor(51, 65, 85)
  const summary = `${patient.name} had a warm and steady week. Memory score rose from 74% to ${patient.memoryScore}% (+8%). She engaged consistently with the AI companion (23 conversations) and completed most reminders (28 of 30). Cognitive games showed strong performance on family-recognition tasks with slight difficulty on event-recall. Continue current medications; increase gentle photo-based conversations, especially around Rohan and Neha.`
  const wrapped = doc.splitTextToSize(summary, w - 100)
  doc.text(wrapped, 50, y + 12)
  y += 12 + wrapped.length * 14

  // Medications table
  y = sectionTitle(doc, y + 10, 'Medication Adherence', [14, 165, 233])
  autoTable(doc, {
    startY: y + 8,
    head: [['Medicine', 'Dose', 'Time', 'Purpose', 'Status']],
    body: medicines.map(m => [m.name, m.dose, m.time, m.purpose, m.status.toUpperCase()]),
    styles: { fontSize: 10, cellPadding: 8 },
    headStyles: { fillColor: [14, 165, 233], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    margin: { left: 40, right: 40 },
  })
  y = doc.lastAutoTable.finalY + 20

  // Weekly performance
  if (y > 680) { doc.addPage(); y = 60 }
  y = sectionTitle(doc, y, 'Weekly Memory & Activity', [20, 184, 166])
  autoTable(doc, {
    startY: y + 8,
    head: [['Day', 'Memory Score', 'Activity Score']],
    body: progressData.weekly.map(d => [d.day, `${d.memory}%`, `${d.activity}%`]),
    styles: { fontSize: 10, cellPadding: 8 },
    headStyles: { fillColor: [20, 184, 166], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    margin: { left: 40, right: 40 },
  })
  y = doc.lastAutoTable.finalY + 20

  // Games
  if (y > 640) { doc.addPage(); y = 60 }
  y = sectionTitle(doc, y, 'Cognitive Games Performance', [139, 92, 246])
  autoTable(doc, {
    startY: y + 8,
    head: [['Game', 'Difficulty', 'Score', 'Accuracy', 'Played', 'Badge']],
    body: games.map(g => [g.name, g.difficulty, g.score, `${g.accuracy}%`, g.played, g.badge]),
    styles: { fontSize: 10, cellPadding: 8 },
    headStyles: { fillColor: [139, 92, 246], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    margin: { left: 40, right: 40 },
  })
  y = doc.lastAutoTable.finalY + 20

  // Reminder completion
  if (y > 640) { doc.addPage(); y = 60 }
  y = sectionTitle(doc, y, 'Reminder Completion (7 days)', [245, 158, 11])
  autoTable(doc, {
    startY: y + 8,
    head: [['Day', 'Completed', 'Missed', 'Rate']],
    body: progressData.reminderCompletion.map(r => {
      const total = r.completed + r.missed
      return [r.day, r.completed, r.missed, total ? `${Math.round((r.completed/total)*100)}%` : '-']
    }),
    styles: { fontSize: 10, cellPadding: 8 },
    headStyles: { fillColor: [245, 158, 11], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [255, 251, 235] },
    margin: { left: 40, right: 40 },
  })
  y = doc.lastAutoTable.finalY + 20

  // Family & Emergency
  if (y > 620) { doc.addPage(); y = 60 }
  y = sectionTitle(doc, y, 'Family Members', [244, 63, 94])
  autoTable(doc, {
    startY: y + 8,
    head: [['Name', 'Relation', 'Location', 'Note']],
    body: family.map(f => [f.name, f.relation, f.location, f.note]),
    styles: { fontSize: 10, cellPadding: 8 },
    headStyles: { fillColor: [244, 63, 94], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [255, 241, 242] },
    margin: { left: 40, right: 40 },
  })
  y = doc.lastAutoTable.finalY + 20

  if (y > 660) { doc.addPage(); y = 60 }
  y = sectionTitle(doc, y, 'Emergency Contacts', [79, 70, 229])
  autoTable(doc, {
    startY: y + 8,
    head: [['Name', 'Phone', 'Primary']],
    body: emergencyContacts.map(c => [c.name, c.phone, c.primary ? 'YES' : '']),
    styles: { fontSize: 10, cellPadding: 8 },
    headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [238, 242, 255] },
    margin: { left: 40, right: 40 },
  })
  y = doc.lastAutoTable.finalY + 20

  // Recommendations
  if (y > 650) { doc.addPage(); y = 60 }
  y = sectionTitle(doc, y, 'Doctor Recommendations', [22, 163, 74])
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10.5); doc.setTextColor(51, 65, 85)
  const recs = [
    '• Continue Donepezil 10mg (evening) — showing positive cognitive trend.',
    '• Add gentle photo-recall sessions (10 min, twice daily) using family photos.',
    '• Encourage Sunday phone call routine — high emotional value observed.',
    '• Review Vitamin D3 adherence — one skip this week.',
    '• Schedule follow-up with Dr. Banerjee within 2 weeks.',
  ]
  recs.forEach((r, i) => { doc.text(r, 50, y + 12 + i * 16) })

  // Footer on all pages
  const pageCount = doc.internal.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) { doc.setPage(i); drawFooter(doc, i, pageCount) }

  doc.save(`SmritiSaathi-Weekly-Report-${patient.name.replace(/\s+/g,'-')}-${now.toISOString().slice(0,10)}.pdf`)
}
